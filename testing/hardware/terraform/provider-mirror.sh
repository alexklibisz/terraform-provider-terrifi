#!/usr/bin/env bash
# Install the pinned Terrifi provider from its GitHub release when the OpenTofu
# registry has not indexed that version yet.
#
# Usage: provider-mirror.sh [--configure] MIRROR_DIR [PLATFORM...]
#
# Reads the provider version pinned in providers.tf. If the registry already
# lists it, does nothing. Otherwise downloads the release zips for each
# PLATFORM (default: this machine's platform), verifies them against the
# release's SHA256SUMS, and unpacks them into an OpenTofu filesystem mirror in
# MIRROR_DIR. With --configure, also rewrites terraform.rc so OpenTofu installs
# Terrifi from the mirror, falling back to the registry for everything else.
# Only use --configure on a disposable checkout such as CI's: it edits a
# tracked file.
#
# The lock file still pins every provider package hash, so a mirrored zip that
# does not match the reviewed release fails `tofu init -lockfile=readonly`.
set -euo pipefail

configure=false
if [ "${1:-}" = "--configure" ]; then
  configure=true
  shift
fi
mirror="${1:?usage: provider-mirror.sh [--configure] MIRROR_DIR [PLATFORM...]}"
shift
platforms=("$@")
if [ ${#platforms[@]} -eq 0 ]; then
  os=$(uname -s | tr '[:upper:]' '[:lower:]')
  case "$(uname -m)" in
    x86_64 | amd64) arch=amd64 ;;
    aarch64 | arm64) arch=arm64 ;;
    *) echo "unsupported architecture: $(uname -m)" >&2; exit 1 ;;
  esac
  platforms=("${os}_${arch}")
fi

dir=$(cd "$(dirname "$0")" && pwd)
version=$(sed -n 's/^[[:space:]]*version[[:space:]]*=[[:space:]]*"\(.*\)".*/\1/p' "$dir/providers.tf")
if [ -z "$version" ]; then
  echo "could not read the provider version from providers.tf" >&2
  exit 1
fi

if curl --fail --silent --show-error \
  "https://registry.opentofu.org/v1/providers/alexklibisz/terrifi/versions" |
  grep -qF "\"$version\""; then
  echo "Registry lists terrifi $version; no mirror needed."
  exit 0
fi

echo "Registry does not list terrifi $version yet; mirroring the GitHub release."
release="https://github.com/alexklibisz/terraform-provider-terrifi/releases/download/v$version"
downloads=$(mktemp -d)
trap 'rm -rf "$downloads"' EXIT
sums="terraform-provider-terrifi_${version}_SHA256SUMS"
curl --fail --silent --show-error --location --output "$downloads/$sums" "$release/$sums"

for platform in "${platforms[@]}"; do
  zip="terraform-provider-terrifi_${version}_${platform}.zip"
  curl --fail --silent --show-error --location --output "$downloads/$zip" "$release/$zip"
  expected=$(awk -v f="$zip" '$2 == f { print $1 }' "$downloads/$sums")
  if [ -z "$expected" ]; then
    echo "$zip is not listed in $sums" >&2
    exit 1
  fi
  if command -v sha256sum >/dev/null; then
    actual=$(sha256sum "$downloads/$zip" | cut -d' ' -f1)
  else
    actual=$(shasum -a 256 "$downloads/$zip" | cut -d' ' -f1)
  fi
  if [ "$actual" != "$expected" ]; then
    echo "$zip checksum mismatch: expected $expected, got $actual" >&2
    exit 1
  fi
  # Unpacked mirror layout. OpenTofu's packed layout (zips directly under the
  # provider directory) does not recognize pre-release versions such as RCs.
  target="$mirror/registry.opentofu.org/alexklibisz/terrifi/$version/$platform"
  rm -rf "$target"
  mkdir -p "$target"
  if command -v unzip >/dev/null; then
    unzip -q "$downloads/$zip" -d "$target"
  elif command -v python3 >/dev/null; then
    python3 -I -m zipfile -e "$downloads/$zip" "$target"
  else
    echo "unzip or python3 is required to unpack $zip" >&2
    exit 1
  fi
  # python3's zipfile does not restore the executable bit.
  chmod +x "$target"/terraform-provider-terrifi*
  echo "Mirrored $zip"
done

if [ "$configure" = true ]; then
  mirror_abs=$(cd "$mirror" && pwd)
  cat >"$dir/terraform.rc" <<EOF
# Generated by provider-mirror.sh: terrifi $version is not in the registry yet.
provider_installation {
  filesystem_mirror {
    path    = "$mirror_abs"
    include = ["registry.opentofu.org/alexklibisz/terrifi"]
  }
  direct {}
}
EOF
  echo "Configured terraform.rc to install terrifi from $mirror_abs"
fi
